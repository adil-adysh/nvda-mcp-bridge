#!/usr/bin/env python3
"""
Protocol code generator — single source of truth → Python + Rust.

Reads:
  docs/protocol/protocol-constants.json   (canonical protocol definition)

Generates:
  addon/globalPlugins/nvdaMcp-bridge/server/protocol_generated.py   (Python)
  rust_mcp_bridge/src/protocol.rs                                    (Rust)
  docs/protocol/common.schema.json                                   (JSON Schema)
  docs/protocol/tool-discovery.schema.json                           (JSON Schema)
  docs/protocol/action-response.schema.json                          (JSON Schema)
  docs/protocol/action-request.schema.json                           (JSON Schema)
  docs/protocol/health.schema.json                                   (JSON Schema)

Usage:
  python scripts/generate_protocol.py
  python scripts/generate_protocol.py --check   (dry-run, exit 1 if files differ)
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Dict, List


# ──────────────────────────────────────────────
#  Load
# ──────────────────────────────────────────────

def load_constants(path: Path) -> Dict[str, Any]:
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


# ──────────────────────────────────────────────
#  Python code generation
# ──────────────────────────────────────────────

def _py_type(field: Dict[str, str]) -> str:
    return field["python_type"]


def _py_default(field: Dict[str, str]) -> str:
    return field["python_default"]


def _py_serialize_name(field: Dict[str, str]) -> str:
    return field.get("python_serialize_name", field["name"])


def generate_python(defn: Dict[str, Any]) -> str:
    proto = defn["protocol"]
    errors = defn["error_codes"]
    http_map = defn["http_status_mapping"]
    cat_rules = defn["category_rules"]
    structs = defn["structs"]

    lines: List[str] = []

    # Header
    lines.append('"""Auto-generated protocol module — do not edit by hand.')
    lines.append("")
    lines.append("Source of truth: docs/protocol/protocol-constants.json")
    lines.append('Generated by:   scripts/generate_protocol.py')
    lines.append('"""')
    lines.append("")
    lines.append("from __future__ import annotations")
    lines.append("")
    lines.append("from dataclasses import dataclass, field")
    lines.append("from typing import Any, Dict, Optional")
    lines.append("")

    # ── constants ──
    lines.append("")
    lines.append("# ── Protocol constants ──")
    lines.append("")
    lines.append(f'DEFAULT_BRIDGE_TOKEN = {json.dumps(proto["default_bridge_token"])}')
    lines.append(f'TOKEN_HEADER = {json.dumps(proto["token_header"])}')
    lines.append(f'BRIDGE_VERSION = {json.dumps(proto["bridge_version"])}')
    lines.append(f'PROTOCOL = {json.dumps(proto["name"])}')
    lines.append(f'PROTOCOL_VERSION = {json.dumps(proto["version"])}')
    lines.append(f"API_LEVEL = {proto['api_level']}")
    lines.append(f"MAX_REQUEST_BODY_SIZE = {proto['max_request_body_size']}")
    lines.append(f"MAX_REQUEST_ID_LENGTH = {proto['max_request_id_length']}")

    # ── error codes ──
    lines.append("")
    lines.append("# ── Error codes ──")
    lines.append("")
    lines.append("# fmt: off")
    lines.append("ERROR_CODES: Dict[int, Dict[str, Any]] = {")
    for code_str, spec in errors.items():
        code = int(code_str)
        parts = [f'"name": {json.dumps(spec["name"])}',
                 f'"category": {json.dumps(spec["category"])}',
                 f'"retry_policy": {json.dumps(spec["retry_policy"])}']
        if "retry_after_ms" in spec:
            parts.append(f'"retry_after_ms": {spec["retry_after_ms"]}')
        lines.append(f"    {code}: {{{', '.join(parts)}}},")
    lines.append("}")
    lines.append("# fmt: on")

    # ── category rules ──
    lines.append("")
    lines.append("# ── Category rules ──")
    lines.append("")
    _allowed = cat_rules['secure_screen_allowed_categories']
    lines.append(f"SECURE_SCREEN_ALLOWED_CATEGORIES = {{{', '.join(repr(c) for c in _allowed)}}}")
    _modal = cat_rules['modal_blocking_blocked_categories']
    lines.append(f"MODAL_BLOCKING_BLOCKED_CATEGORIES = {{{', '.join(repr(c) for c in _modal)}}}")
    _menu = cat_rules['menu_open_blocked_categories']
    lines.append(f"MENU_OPEN_BLOCKED_CATEGORIES = {{{', '.join(repr(c) for c in _menu)}}}")

    # ── dataclasses ──
    lines.append("")
    lines.append("# ── Protocol structs (dataclasses) ──")
    lines.append("")

    for struct_name, struct_def in structs.items():
        desc = struct_def.get("description", "")
        if desc:
            lines.append("@dataclass")
            lines.append(f"class {struct_name}:")
            lines.append(f'    """{desc}"""')
            field_lines = []
            for fld in struct_def["fields"]:
                py_name = fld["name"]
                py_type = _py_type(fld)
                py_def = _py_default(fld)
                # Mutable defaults (dict, list) must use default_factory
                if py_def in ("{}", "[]"):
                    factory = "dict" if py_def == "{}" else "list"
                    field_lines.append(f"    {py_name}: {py_type} = field(default_factory={factory})")
                else:
                    field_lines.append(f"    {py_name}: {py_type} = field(default={py_def})")
            if not field_lines:
                lines.append("    pass")
            else:
                lines.extend(field_lines)
            lines.append("")

    # ── HTTP status mapping ──
    lines.append("")
    lines.append("# ── HTTP status mapping ──")
    lines.append("")
    lines.append("def http_status_from_error_code(code: int) -> int:")
    rules = http_map["rules"]
    lines.append("    # fmt: off")
    for i, rule in enumerate(rules):
        if "code" in rule:
            lines.append(f"    if code == {rule['code']}:")
        else:
            lines.append(f"    if {rule['min']} <= code <= {rule['max']}:")
        lines.append(f"        return {rule['http_status']}")
    lines.append(f"    return {http_map['default']}")
    lines.append("    # fmt: on")

    # ── validation ──
    lines.append("")
    lines.append("# ── Validation ──")
    lines.append("")
    lines.append("")
    lines.append("def validate_tools_discovery_payload(payload: Dict[str, Any]) -> None:")
    lines.append('    """Validate a /tools discovery response against the protocol contract."""')
    lines.append("    required_top = {")
    lines.append('        "protocol",')
    lines.append('        "protocol_version",')
    lines.append('        "bridge_version",')
    lines.append('        "api_level",')
    lines.append('        "types",')
    lines.append('        "tools",')
    lines.append('        "count",')
    lines.append("    }")
    lines.append("    missing_top = required_top - set(payload.keys())")
    lines.append("    if missing_top:")
    lines.append('        raise RuntimeError(f"tools payload missing required fields: {chr(39).join(sorted(missing_top))}")')
    lines.append("")
    lines.append('    if payload.get("protocol") != PROTOCOL:')
    lines.append('        raise RuntimeError("tools payload has invalid protocol")')
    lines.append('    if payload.get("protocol_version") != PROTOCOL_VERSION:')
    lines.append('        raise RuntimeError("tools payload has invalid protocol_version")')
    lines.append('    if payload.get("api_level") != API_LEVEL:')
    lines.append('        raise RuntimeError("tools payload has invalid api_level")')
    lines.append("")
    lines.append('    types = payload.get("types")')
    lines.append('    tools = payload.get("tools")')
    lines.append('    count = payload.get("count")')
    lines.append("    if not isinstance(types, dict) or not types:")
    lines.append('        raise RuntimeError("tools payload has invalid or empty types registry")')
    lines.append("    if not isinstance(tools, list):")
    lines.append('        raise RuntimeError("tools payload has invalid tools list")')
    lines.append("    if not isinstance(count, int) or count != len(tools):")
    lines.append('        raise RuntimeError("tools payload count mismatch")')
    lines.append("")
    lines.append("    for type_name in types.keys():")
    lines.append("        if not isinstance(type_name, str) or not type_name or not type_name[0].isupper():")
    lines.append('            raise RuntimeError(f"invalid output type name in types registry: {type_name!r}")')
    lines.append("")
    lines.append("    used_types = set()")
    lines.append("    for tool in tools:")
    lines.append("        if not isinstance(tool, dict):")
    lines.append('            raise RuntimeError("tool entry must be an object")')
    lines.append('        for key in ("name", "description", "inputSchema", "outputType", "version", "category"):')
    lines.append("            if key not in tool:")
    lines.append('                raise RuntimeError(f"tool entry missing required field: {key}")')
    lines.append('        if "outputSchema" in tool:')
    lines.append('            raise RuntimeError("outputSchema is forbidden in protocol v1")')
    lines.append("")
    lines.append('        output_type = tool.get("outputType")')
    lines.append("        if not isinstance(output_type, str) or not output_type:")
    lines.append('            raise RuntimeError("tool outputType must be a non-empty string")')
    lines.append("        if output_type not in types:")
    lines.append('            raise RuntimeError(f"tool references unknown outputType: {output_type}")')
    lines.append("        used_types.add(output_type)")
    lines.append("")
    lines.append("    unused_types = set(types.keys()) - used_types")
    lines.append("    if unused_types:")
    lines.append('        raise RuntimeError("unused output types are not allowed")')
    lines.append("")
    lines.append("")
    lines.append("def build_tools_payload(tools: list[Dict[str, Any]], types: Dict[str, Any]) -> Dict[str, Any]:")
    lines.append('    """Build a /tools discovery response payload."""')
    lines.append('    used_types = {tool.get("outputType") for tool in tools if isinstance(tool, dict) and tool.get("outputType")}')
    lines.append('    filtered_types = {k: v for k, v in types.items() if k in used_types}')
    lines.append("    return {")
    lines.append('        "protocol": PROTOCOL,')
    lines.append('        "protocol_version": PROTOCOL_VERSION,')
    lines.append('        "bridge_version": BRIDGE_VERSION,')
    lines.append('        "api_level": API_LEVEL,')
    lines.append('        "types": filtered_types,')
    lines.append('        "tools": tools,')
    lines.append('        "count": len(tools),')
    lines.append("    }")

    return "\n".join(lines) + "\n"


