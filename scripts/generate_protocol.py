def resolve_paths(repo_root: Path) -> Dict[str, Path]:
    return {
        "repo_root": repo_root,
        "constants": repo_root / "docs" / "protocol" / "protocol-constants.json",
        "python_out": repo_root / "addon" / "globalPlugins" / "nvdaMcp-bridge" / "server" / "protocol_generated.py",
        "rust_out": repo_root / "rust_mcp_bridge" / "src" / "protocol.rs",
        "common_schema": repo_root / "docs" / "protocol" / "common.schema.json",
        "tool_discovery_schema": repo_root / "docs" / "protocol" / "tool-discovery.schema.json",
        "action_request_schema": repo_root / "docs" / "protocol" / "action-request.schema.json",
        "action_response_schema": repo_root / "docs" / "protocol" / "action-response.schema.json",
        "health_schema": repo_root / "docs" / "protocol" / "health.schema.json",
    }


def write_if_changed(path: Path, content: str) -> bool:
    """Write content to path. Returns True if changed."""
    if path.exists():
        existing = path.read_text(encoding="utf-8")
        if existing == content:
            return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return True


def write_json_if_changed(path: Path, content: Dict[str, Any]) -> bool:
    json_str = json.dumps(content, indent=2, ensure_ascii=False) + "\n"
    return write_if_changed(path, json_str)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate protocol code from single source of truth.")
    parser.add_argument(
        "--check",
        action="store_true",
        help="Dry-run: exit 1 if any generated file differs from on-disk version.",
    )
    parser.add_argument(
        "--repo-root",
        default=None,
        help="Path to repository root. Defaults to repo root (parent of scripts/).",
    )
    args = parser.parse_args()

    repo_root = Path(args.repo_root) if args.repo_root else Path(__file__).resolve().parent.parent
    paths = resolve_paths(repo_root)

    if not paths["constants"].exists():
        print(f"ERROR: protocol-constants.json not found at {paths['constants']}", file=sys.stderr)
        return 2

    defn = load_constants(paths["constants"])

    # Generate all outputs
    outputs: Dict[Path, str] = {
        paths["python_out"]: generate_python(defn),
        paths["rust_out"]: generate_rust(defn),
    }

    json_outputs: Dict[Path, Dict[str, Any]] = {
        paths["common_schema"]: generate_common_schema(defn),
        paths["tool_discovery_schema"]: generate_tool_discovery_schema(defn),
        paths["action_request_schema"]: generate_action_request_schema(defn),
        paths["action_response_schema"]: generate_action_response_schema(defn),
        paths["health_schema"]: generate_health_schema(defn),
    }

    changed = False

    for path, content in outputs.items():
        if args.check:
            if path.exists() and path.read_text(encoding="utf-8") != content:
                print(f"WOULD CHANGE: {path.relative_to(repo_root)}", file=sys.stderr)
                changed = True
        else:
            file_changed = write_if_changed(path, content)
            if file_changed:
                print(f"WRITE: {path.relative_to(repo_root)}")
                changed = True

    for path, content in json_outputs.items():
        if args.check:
            if path.exists():
                existing = json.loads(path.read_text(encoding="utf-8"))
                if existing != content:
                    print(f"WOULD CHANGE: {path.relative_to(repo_root)}", file=sys.stderr)
                    changed = True
        else:
            file_changed = write_json_if_changed(path, content)
            if file_changed:
                print(f"WRITE: {path.relative_to(repo_root)}")
                changed = True

    if not changed:
        print("All generated files are up to date.")

    if args.check and changed:
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
