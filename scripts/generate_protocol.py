RUST_TYPE_MAP = {
    "String": "String",
    "bool": "bool",
    "u32": "u32",
    "u64": "u64",
    "f64": "f64",
    "usize": "usize",
    "Option<String>": "Option<String>",
    "Option<bool>": "Option<bool>",
    "Option<u32>": "Option<u32>",
    "Option<u64>": "Option<u64>",
    "Option<f64>": "Option<f64>",
    "Option<usize>": "Option<usize>",
    "Map<String, Value>": "Map<String, Value>",
    "Option<Map<String, Value>>": "Option<Map<String, Value>>",
    "Option<Value>": "Option<Value>",
    "Vec<BridgeToolDef>": "Vec<BridgeToolDef>",
    "Option<BridgeMeta>": "Option<BridgeMeta>",
    "Option<NvdaStatusSnapshot>": "Option<NvdaStatusSnapshot>",
    "Option<BridgeError>": "Option<BridgeError>",
    "Option<BridgeToolConstraints>": "Option<BridgeToolConstraints>",
    "ErrorCode": "ErrorCode",
}


def _rust_type(field: Dict[str, str]) -> str:
    t = field["type"]
    return RUST_TYPE_MAP.get(t, t)


def generate_rust(defn: Dict[str, Any]) -> str:
    proto = defn["protocol"]
    structs = defn["structs"]

    lines: List[str] = []

    # Header
    lines.append("// Auto-generated protocol module — do not edit by hand.")
    lines.append("//")
    lines.append("// Source of truth: docs/protocol/protocol-constants.json")
    lines.append("// Generated by:   scripts/generate_protocol.py")
    lines.append("")
    lines.append("use serde::{Deserialize, Serialize};")
    lines.append("use serde_json::{Map, Value};")
    lines.append("")

    # ── constants ──
    lines.append("// ── Protocol constants ──")
    lines.append("")
    lines.append("#[allow(dead_code)]")
    lines.append(f'pub const PROTOCOL_NAME: &str = {json.dumps(proto["name"])};')
    lines.append("#[allow(dead_code)]")
    lines.append(f'pub const PROTOCOL_VERSION: &str = {json.dumps(proto["version"])};')
    lines.append("#[allow(dead_code)]")
    lines.append(f'pub const BRIDGE_VERSION: &str = {json.dumps(proto["bridge_version"])};')
    lines.append(f"pub const API_LEVEL: u32 = {proto['api_level']};")
    lines.append(f'pub const TOKEN_HEADER: &str = {json.dumps(proto["token_header"])};')
    lines.append("#[allow(dead_code)]")
    lines.append(f"pub const MAX_REQUEST_ID_LENGTH: usize = {proto['max_request_id_length']};")
    lines.append("")

    # ── ErrorCode helper ──
    lines.append("/// Flexible error code — accepts both integer (protocol v1) and string (legacy).")
    lines.append("#[derive(Debug, Clone, Serialize, Default)]")
    lines.append("pub struct ErrorCode(pub String);")
    lines.append("")
    lines.append("impl ErrorCode {")
    lines.append("    pub fn as_str(&self) -> &str {")
    lines.append("        &self.0")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    lines.append("impl<'de> serde::Deserialize<'de> for ErrorCode {")
    lines.append("    fn deserialize<D>(deserializer: D) -> std::result::Result<Self, D::Error>")
    lines.append("    where")
    lines.append("        D: serde::Deserializer<'de>,")
    lines.append("    {")
    lines.append("        use serde::de;")
    lines.append("        struct ErrorCodeVisitor;")
    lines.append("        impl de::Visitor<'_> for ErrorCodeVisitor {")
    lines.append("            type Value = ErrorCode;")
    lines.append("            fn expecting(&self, f: &mut std::fmt::Formatter) -> std::fmt::Result {")
    lines.append('                f.write_str("an integer or string error code")')
    lines.append("            }")
    lines.append("            fn visit_i64<E: de::Error>(self, v: i64) -> std::result::Result<ErrorCode, E> {")
    lines.append("                Ok(ErrorCode(v.to_string()))")
    lines.append("            }")
    lines.append("            fn visit_u64<E: de::Error>(self, v: u64) -> std::result::Result<ErrorCode, E> {")
    lines.append("                Ok(ErrorCode(v.to_string()))")
    lines.append("            }")
    lines.append("            fn visit_str<E: de::Error>(self, v: &str) -> std::result::Result<ErrorCode, E> {")
    lines.append("                Ok(ErrorCode(v.to_string()))")
    lines.append("            }")
    lines.append("        }")
    lines.append("        deserializer.deserialize_any(ErrorCodeVisitor)")
    lines.append("    }")
    lines.append("}")
    lines.append("")

    # ── Structs ──
    lines.append("// ── Protocol structs ──")
    lines.append("")

    for struct_name, struct_def in structs.items():
        desc = struct_def.get("description", "")

        lines.append(f"/// {desc}")
        lines.append("#[derive(Debug, Deserialize, Serialize, Clone, Default)]")

        # If any field has serde_rename, we need a custom Deserialize; otherwise just derive
        needs_custom_serde = any("serde_rename" in fld for fld in struct_def["fields"])
        if needs_custom_serde:
            lines.append(f"pub struct {struct_name} {{")
        else:
            lines.append(f"pub struct {struct_name} {{")

        for fld in struct_def["fields"]:
            rust_name = fld["name"]
            rust_type = _rust_type(fld)
            serde_rename = fld.get("serde_rename")
            serde_default = fld.get("serde_default", False)

            attrs = []
            if serde_rename:
                attrs.append(f'rename = "{serde_rename}"')
            if serde_default:
                attrs.append("default")

            if attrs:
                lines.append(f'    #[serde({", ".join(attrs)})]')
            lines.append(f"    pub {rust_name}: {rust_type},")

        lines.append("}")
        lines.append("")

    # ── validation ──
    lines.append("// ── Validation ──")
    lines.append("")
    lines.append("/// Validate a /tools discovery response against the protocol contract.")
    lines.append("pub fn validate_tools_payload(protocol: &str, protocol_version: &str,")
    lines.append("    bridge_version: &str, api_level: u32, count: usize, actual_count: usize,")
    lines.append(") -> Result<(), String> {")
    lines.append('    if protocol != PROTOCOL_NAME {')
    proto_name_str = proto["name"]
    lines.append(f'        return Err(format!("Bridge protocol mismatch: expected \\"{proto_name_str}\\", got {{}}", protocol));')
    lines.append("    }")
    lines.append("    if api_level != API_LEVEL {")
    lines.append('        return Err(format!("Bridge API level mismatch: expected {}, got {}", API_LEVEL, api_level));')
    lines.append("    }")
    lines.append("    if protocol_version.trim().is_empty() {")
    lines.append('        return Err("Bridge protocol_version cannot be empty".into());')
    lines.append("    }")
    lines.append("    if bridge_version.trim().is_empty() {")
    lines.append('        return Err("Bridge bridge_version cannot be empty".into());')
    lines.append("    }")
    lines.append("    if count != actual_count {")
    lines.append('        return Err(format!("Bridge tools count mismatch: declared {}, actual {}", count, actual_count));')
    lines.append("    }")
    lines.append("    Ok(())")
    lines.append("}")

    return "\n".join(lines) + "\n"


