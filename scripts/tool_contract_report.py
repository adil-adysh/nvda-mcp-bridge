#!/usr/bin/env python3
"""Print the agent-facing tool contract for the NVDA MCP bridge.

This is the Phase 0 inventory: every tool's input schema, output schema,
required fields, defaults and schema size. Run it after changing a model and
commit the generated table in ``docs/TOOL_CONTRACT.md`` so a contract change is
visible in review.
"""

from __future__ import annotations

import argparse
import dataclasses
import importlib
import json
from pathlib import Path

from generate_bridge_schema import bootstrap_addon_package


def build_report(addon_root: Path) -> str:
	bootstrap_addon_package(addon_root)
	registry = importlib.import_module("nvdaMcpBridge.tools.registry").NVDA_TOOLS_REGISTRY

	lines = [
		"# NVDA MCP tool contract",
		"",
		"Generated by `python scripts/tool_contract_report.py`; do not edit by hand.",
		"",
		"| Tool | Input required | Input defaults | Input bytes | Output bytes |",
		"|---|---|---|---:|---:|",
	]
	for meta in registry.list_tools():
		tool = registry.get(meta.name, meta.version)
		input_model = tool.get_input_schema().model
		input_schema = tool.get_input_schema().to_json_schema()
		output_schema = tool.get_output_schema().to_json_schema()
		required = input_schema.get("required", [])
		defaults = {
			field.name: field.default
			for field in dataclasses.fields(input_model)
			if field.default is not dataclasses.MISSING
		}
		defaults_text = ", ".join(f"{key}={value!r}" for key, value in defaults.items()) or "—"
		lines.append(
			f"| `{meta.name}` | {', '.join(required) or '—'} | {defaults_text} | "
			f"{len(json.dumps(input_schema))} | {len(json.dumps(output_schema))} |"
		)

	lines.extend(
		[
			"",
			"## Invariants",
			"",
			"- References are strings matching `^[a-z][a-z0-9]*$`; every action result carries `state_version`.",
			"- `observe` returns `refs` and `top_window`; detail is `summary` unless requested.",
			"- Inputs reject unknown fields; outputs are validated against their published schema.",
			"- `press` normalizes aliases and reports `requested` and `normalized_keys`.",
			"- Every JSON-Schema property that has a bound is enforced at runtime too.",
			"",
		]
	)
	return "\n".join(lines)


def main() -> int:
	parser = argparse.ArgumentParser(description=__doc__)
	parser.add_argument("--output", "-o", default=None)
	args = parser.parse_args()
	repo_root = Path(__file__).resolve().parent.parent
	addon_root = repo_root / "addon" / "globalPlugins" / "nvdaMcp-bridge"
	report = build_report(addon_root.resolve())
	if args.output:
		Path(args.output).write_text(report, encoding="utf-8")
	else:
		print(report)
	return 0


if __name__ == "__main__":
	raise SystemExit(main())
